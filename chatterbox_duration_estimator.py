def _control_points(
    rng: random.Random,
    variants: int,
    exag_min: float,
    exag_max: float,
    cfg_min: float,
    cfg_max: float,
) -> list[tuple[float, float]]:
    # Anchor points make the response surface identifiable; jittered points
    # cover the rest continuously.
    anchors = [
        (0.50, 0.50),
        (0.35, 0.35),
        (0.65, 0.35),
        (0.40, 0.65),
        (0.70, 0.60),
    ]
    pts: list[tuple[float, float]] = []
    for e, c in anchors:
        if len(pts) >= variants:
            break
        if exag_min <= e <= exag_max and cfg_min <= c <= cfg_max:
            pts.append((e, c))
    while len(pts) < variants:
        pts.append((
            rng.uniform(exag_min, exag_max),
            rng.uniform(cfg_min, cfg_max),
        ))
    rng.shuffle(pts)
    return pts[:variants]


def collect_data(args) -> None:
    rng = random.Random(args.random_seed)
    corpus = read_corpus(args.corpus, max_chars=args.max_chars) if args.corpus else []

    texts: list[str] = []
    if corpus:
        rng.shuffle(corpus)
        texts.extend(corpus[: args.texts])

    seen = {normalize_key(x) for x in texts}
    attempts = 0
    while len(texts) < args.texts and attempts < args.texts * 30:
        attempts += 1
        t = synthetic_text(rng, args.min_words, args.max_words)
        k = normalize_key(t)
        if k not in seen:
            seen.add(k)
            texts.append(t)

    if len(texts) < args.texts:
        raise RuntimeError(f"Could only create {len(texts)} unique texts.")

    print(f"Loading Chatterbox on {args.device} ...", flush=True)
    probe = ChatterboxTokenProbe(device=args.device, voice_ref=args.voice_ref)
    print(
        f"Collecting {len(texts)} texts × {args.variants_per_text} variants "
        f"= {len(texts) * args.variants_per_text} labels",
        flush=True,
    )

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    exists = out.exists() and out.stat().st_size > 0
    mode = "a" if args.append else "w"

    with out.open(mode, encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=DATA_FIELDS)
        if mode == "w" or not exists:
            writer.writeheader()

        n = 0
        t0 = time.time()
        waveform_checks = 0
        for ti, text in enumerate(texts):
            text_id = normalize_key(text)
            cps = _control_points(
                rng,
                args.variants_per_text,
                args.exag_min,
                args.exag_max,
                args.cfg_min,
                args.cfg_max,
            )

            for vi, (exag, cfg) in enumerate(cps):
                if args.seed_mode == "fixed":
                    seed = args.tts_seed
                else:
                    seed = args.tts_seed + ti * 1009 + vi * 97

                tokens = probe.probe_tokens(
                    text=text,
                    exaggeration=exag,
                    cfg_weight=cfg,
                    temperature=args.temperature,
                    repetition_penalty=args.repetition_penalty,
                    min_p=args.min_p,
                    top_p=args.top_p,
                    seed=seed,
                    max_new_tokens=args.max_new_tokens,
                )
                token_count = int(tokens.numel())
                duration = token_count / float(probe.token_rate)

                wav_duration = ""
                wav_error = ""
                if args.waveform_check_rate > 0 and rng.random() < args.waveform_check_rate:
                    wd = probe.waveform_duration_from_tokens(tokens)
                    waveform_checks += 1
                    wav_duration = f"{wd:.9f}"
                    wav_error = f"{100.0 * abs(wd - duration) / max(1e-9, wd):.6f}"

                writer.writerow({
                    "text_id": text_id,
                    "text": text,
                    "exaggeration": f"{exag:.6f}",
                    "cfg_weight": f"{cfg:.6f}",
                    "seed": seed,
                    "temperature": args.temperature,
                    "repetition_penalty": args.repetition_penalty,
                    "min_p": args.min_p,
                    "top_p": args.top_p,
                    "speech_tokens": token_count,
                    "token_rate": probe.token_rate,
                    "duration_s": f"{duration:.9f}",
                    "waveform_duration_s": wav_duration,
                    "waveform_error_pct": wav_error,
                })
                f.flush()
                n += 1
                if n % 25 == 0:
                    elapsed = time.time() - t0
                    rate = n / max(1e-6, elapsed)
                    print(
                        f"  {n}/{len(texts) * args.variants_per_text} "
                        f"({rate:.2f} labels/s)",
                        flush=True,
                    )

    print(f"Wrote {n} labels to {out}")
    if waveform_checks:
        print(f"Performed {waveform_checks} token→waveform duration checks.")
    probe.close()


