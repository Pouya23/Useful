_CMU = None


def _get_cmudict():
    global _CMU
    if _CMU is None:
        try:
            import cmudict
            _CMU = cmudict.dict()
        except Exception:
            _CMU = {}
    return _CMU


def heuristic_syllables(word: str) -> int:
    w = re.sub(r"[^a-z]", "", word.lower())
    if not w:
        return 0
    groups = len(VOWEL_GROUP_RE.findall(w))
    if len(w) > 3 and w.endswith("e") and not w.endswith(("le", "ye")):
        groups -= 1
    if w.endswith("ed") and len(w) > 4 and not w.endswith(("ted", "ded")):
        groups -= 1
    return max(1, groups)


def pronunciation_stats(text: str) -> dict[str, float]:
    cmu = _get_cmudict()
    toks = [re.sub(r"[^A-Za-z']", "", w).lower() for w in words(text)]
    toks = [w for w in toks if w and any(ch.isalpha() for ch in w)]

    phoneme_count = 0
    vowel_phonemes = 0
    stressed = 0
    cmu_hits = 0
    syllables = 0

    for w in toks:
        lookup = w
        if lookup.endswith("'s"):
            lookup = lookup[:-2]
        prons = cmu.get(lookup)
        if prons:
            pron = prons[0]
            cmu_hits += 1
            phoneme_count += len(pron)
            v = sum(1 for p in pron if p and p[-1:].isdigit())
            vowel_phonemes += v
            syllables += v
            stressed += sum(1 for p in pron if p.endswith(("1", "2")))
        else:
            syl = heuristic_syllables(w)
            syllables += syl
            vowel_phonemes += syl
            # A spelling-based phoneme-count approximation.
            phoneme_count += max(syl, round(0.68 * len(w) + 0.6 * syl))

    n = max(1, len(toks))
    return {
        "phoneme_count": float(phoneme_count),
        "vowel_phonemes": float(vowel_phonemes),
        "stressed_syllables": float(stressed),
        "syllable_count": float(syllables),
        "cmu_hit_ratio": float(cmu_hits / n),
        "phonemes_per_word": float(phoneme_count / n),
        "syllables_per_word": float(syllables / n),
    }


def text_feature_dict(
    text: str,
    exaggeration: float,
    cfg_weight: float,
) -> dict[str, float]:
    text = normalize_space(text)
    toks = words(text)
    alpha_words = [w for w in toks if any(c.isalpha() for c in w)]
    lengths = [len(re.sub(r"[^A-Za-z]", "", w)) for w in alpha_words]
    n_words = len(toks)
    n_alpha_words = len(alpha_words)
    n_chars = len(text)
    n_letters = sum(c.isalpha() for c in text)
    n_digits = sum(c.isdigit() for c in text)
    n_spaces = sum(c.isspace() for c in text)
    n_upper = sum(c.isupper() for c in text)
    n_lower = sum(c.islower() for c in text)

    sentence_end = sum(text.count(x) for x in ".!?")
    comma = text.count(",")
    semicolon = text.count(";")
    colon = text.count(":")
    dash = text.count("-") + text.count("—") + text.count("–")
    quote = sum(text.count(x) for x in ['"', "“", "”"])
    apostrophe = text.count("'") + text.count("’")
    parens = sum(text.count(x) for x in "()[]{}")
    slash = text.count("/") + text.count("\\")
    ellipsis = text.count("...") + text.count("…")
    newline = str(text).count("\n")

    p = pronunciation_stats(text)

    unique_words = len({w.lower() for w in toks})
    mean_word_len = float(np.mean(lengths)) if lengths else 0.0
    std_word_len = float(np.std(lengths)) if lengths else 0.0
    max_word_len = max(lengths) if lengths else 0

    f: dict[str, float] = {
        "chars": float(n_chars),
        "letters": float(n_letters),
        "digits": float(n_digits),
        "spaces": float(n_spaces),
        "words": float(n_words),
        "alpha_words": float(n_alpha_words),
        "unique_words": float(unique_words),
        "unique_word_ratio": float(unique_words / max(1, n_words)),
        "mean_word_len": mean_word_len,
        "std_word_len": std_word_len,
        "max_word_len": float(max_word_len),
        "short_words_1_3": float(sum(1 <= x <= 3 for x in lengths)),
        "medium_words_4_6": float(sum(4 <= x <= 6 for x in lengths)),
        "long_words_7_9": float(sum(7 <= x <= 9 for x in lengths)),
        "very_long_words_10p": float(sum(x >= 10 for x in lengths)),
        "sentence_end": float(sentence_end),
        "commas": float(comma),
        "semicolons": float(semicolon),
        "colons": float(colon),
        "dashes": float(dash),
        "quotes": float(quote),
        "apostrophes": float(apostrophe),
        "parens": float(parens),
        "slashes": float(slash),
        "ellipsis": float(ellipsis),
        "newlines": float(newline),
        "acronyms": float(len(ACRONYM_RE.findall(text))),
        "numbers": float(len(NUMBER_RE.findall(text))),
        "urls": float(len(URL_RE.findall(text))),
        "emails": float(len(EMAIL_RE.findall(text))),
        "uppercase_ratio": float(n_upper / max(1, n_letters)),
        "lowercase_ratio": float(n_lower / max(1, n_letters)),
        "digit_ratio": float(n_digits / max(1, n_chars)),
        "punctuation_total": float(sum(not c.isalnum() and not c.isspace() for c in text)),
        "clause_marks": float(comma + semicolon + colon + dash),
        "pause_marks": float(sentence_end + comma + semicolon + colon + ellipsis),
        "exaggeration": float(exaggeration),
        "cfg_weight": float(cfg_weight),
        "exag_sq": float(exaggeration * exaggeration),
        "cfg_sq": float(cfg_weight * cfg_weight),
        "exag_x_cfg": float(exaggeration * cfg_weight),
        "words_x_exag": float(n_words * exaggeration),
        "words_x_cfg": float(n_words * cfg_weight),
        "chars_x_exag": float(n_chars * exaggeration),
        "chars_x_cfg": float(n_chars * cfg_weight),
    }
    f.update(p)

    # Letter-distribution features help with pronunciation on words absent from CMUdict.
    lower = text.lower()
    denom = max(1, n_letters)
    for ch in "abcdefghijklmnopqrstuvwxyz":
        f[f"letter_{ch}_ratio"] = float(lower.count(ch) / denom)

    # Densities are useful for extrapolating across text length.
    wden = max(1, n_words)
    for key in (
        "sentence_end", "commas", "semicolons", "colons", "dashes",
        "ellipsis", "numbers", "acronyms", "pause_marks", "syllable_count",
        "phoneme_count",
    ):
        f[f"{key}_per_word"] = float(f[key] / wden)

    return f


def heuristic_duration(text: str, exaggeration: float = 0.5, cfg_weight: float = 0.5) -> float:
    """
    Rule-based fallback. It is intentionally conservative and is NOT the
    precision estimator.
    """
    f = text_feature_dict(text, exaggeration, cfg_weight)
    syllables = f["syllable_count"]
    # Rough neutral speech rate, then small control corrections in the
    # direction documented for Chatterbox (higher exaggeration tends faster;
    # lower CFG is commonly used to slow/steady pace).
    syllables_per_second = 4.35
    speed = 1.0 + 0.12 * (exaggeration - 0.5) + 0.10 * (cfg_weight - 0.5)
    speed = max(0.70, min(1.30, speed))
    lexical = syllables / (syllables_per_second * speed)

    pauses = (
        0.12 * f["commas"]
        + 0.18 * f["semicolons"]
        + 0.16 * f["colons"]
        + 0.24 * f["sentence_end"]
        + 0.20 * f["ellipsis"]
    )
    return max(0.20, lexical + pauses)


