@dataclass
class Record:
    text_id: str
    text: str
    exaggeration: float
    cfg_weight: float
    speech_tokens: float
    duration_s: float


def load_records(path: str | Path) -> list[Record]:
    records: list[Record] = []
    with Path(path).open("r", encoding="utf-8", newline="") as f:
        for row in csv.DictReader(f):
            records.append(Record(
                text_id=row.get("text_id") or normalize_key(row["text"]),
                text=row["text"],
                exaggeration=float(row["exaggeration"]),
                cfg_weight=float(row["cfg_weight"]),
                speech_tokens=float(row["speech_tokens"]),
                duration_s=float(row["duration_s"]),
            ))
    if not records:
        raise ValueError("Dataset is empty.")
    return records


def regression_metrics(y_true_tokens: np.ndarray, y_pred_tokens: np.ndarray, token_rate: float = 25.0):
    y_true_tokens = np.asarray(y_true_tokens, dtype=float)
    y_pred_tokens = np.asarray(y_pred_tokens, dtype=float)
    true_s = y_true_tokens / token_rate
    pred_s = y_pred_tokens / token_rate
    err = pred_s - true_s
    ape = np.abs(err) / np.maximum(1e-9, true_s) * 100.0

    return {
        "n": int(len(y_true_tokens)),
        "mae_seconds": float(np.mean(np.abs(err))),
        "median_abs_seconds": float(np.median(np.abs(err))),
        "rmse_seconds": float(np.sqrt(np.mean(err ** 2))),
        "mape_percent": float(np.mean(ape)),
        "median_ape_percent": float(np.median(ape)),
        "p90_ape_percent": float(np.percentile(ape, 90)),
        "p95_ape_percent": float(np.percentile(ape, 95)),
        "p99_ape_percent": float(np.percentile(ape, 99)),
        "max_ape_percent": float(np.max(ape)),
        "within_1pct_percent": float(100.0 * np.mean(ape < 1.0)),
        "within_2pct_percent": float(100.0 * np.mean(ape < 2.0)),
        "within_5pct_percent": float(100.0 * np.mean(ape < 5.0)),
    }


class DurationEnsemble:
    """
    Ensemble:
      * sparse lexical Ridge: char + word TF-IDF + dense features
      * ExtraTrees on dense linguistic/control features
      * HistGradientBoosting on dense features
      * optional LightGBM on dense features

    Base models predict log(speech_token_count), then a tiny linear blender
    combines them.
    """

    def __init__(self, random_seed: int = 1234):
        self.random_seed = random_seed
        self.feature_names: list[str] = []
        self.char_vec = None
        self.word_vec = None
        self.scaler = None
        self.ridge = None
        self.extra = None
        self.hist = None
        self.lgbm = None
        self.model_names: list[str] = []
        self.blender_coef: Optional[np.ndarray] = None
        self.blender_intercept: float = 0.0
        self.token_rate: float = 25.0
        self.metadata: dict = {}

    def _dense_matrix(self, records: Sequence[Record], fit_names: bool = False) -> np.ndarray:
        dicts = [
            text_feature_dict(r.text, r.exaggeration, r.cfg_weight)
            for r in records
        ]
        if fit_names:
            self.feature_names = sorted(dicts[0].keys())
        return np.asarray(
            [[d.get(k, 0.0) for k in self.feature_names] for d in dicts],
            dtype=np.float32,
        )

    def _text_list(self, records: Sequence[Record]) -> list[str]:
        return [r.text for r in records]

    def fit_base(self, records: Sequence[Record], use_lightgbm: bool = True) -> None:
        from scipy.sparse import csr_matrix, hstack
        from sklearn.ensemble import ExtraTreesRegressor, HistGradientBoostingRegressor
        from sklearn.feature_extraction.text import TfidfVectorizer
        from sklearn.linear_model import Ridge
        from sklearn.preprocessing import StandardScaler

        y = np.log(np.maximum(1.0, np.asarray([r.speech_tokens for r in records], dtype=np.float64)))
        Xd = self._dense_matrix(records, fit_names=True)
        texts = self._text_list(records)

        min_df = 2 if len(records) >= 200 else 1
        self.char_vec = TfidfVectorizer(
            analyzer="char_wb",
            ngram_range=(2, 5),
            min_df=min_df,
            max_features=35000,
            sublinear_tf=True,
            dtype=np.float32,
        )
        self.word_vec = TfidfVectorizer(
            analyzer="word",
            ngram_range=(1, 2),
            min_df=min_df,
            max_features=18000,
            sublinear_tf=True,
            strip_accents="unicode",
            dtype=np.float32,
        )

        Xc = self.char_vec.fit_transform(texts)
        Xw = self.word_vec.fit_transform(texts)
        self.scaler = StandardScaler()
        Xds = self.scaler.fit_transform(Xd).astype(np.float32)
        Xs = hstack([Xc, Xw, csr_matrix(Xds)], format="csr")

        self.ridge = Ridge(alpha=4.0, solver="lsqr", tol=1e-5)
        self.ridge.fit(Xs, y)

        self.extra = ExtraTreesRegressor(
            n_estimators=600,
            min_samples_leaf=1,
            max_features=0.90,
            n_jobs=-1,
            random_state=self.random_seed,
        )
        self.extra.fit(Xd, y)

        self.hist = HistGradientBoostingRegressor(
            learning_rate=0.045,
            max_iter=500,
            max_leaf_nodes=31,
            l2_regularization=0.35,
            min_samples_leaf=max(8, min(25, len(records) // 80)),
            random_state=self.random_seed,
        )
        self.hist.fit(Xd, y)

        self.lgbm = None
        if use_lightgbm:
            try:
                from lightgbm import LGBMRegressor
                self.lgbm = LGBMRegressor(
                    objective="regression",
                    n_estimators=1200,
                    learning_rate=0.025,
                    num_leaves=31,
                    max_depth=-1,
                    min_child_samples=max(10, min(30, len(records) // 70)),
                    subsample=0.90,
                    colsample_bytree=0.90,
                    reg_alpha=0.05,
                    reg_lambda=0.50,
                    random_state=self.random_seed,
                    n_jobs=-1,
                    verbosity=-1,
                )
                self.lgbm.fit(Xd, y)
            except Exception as e:
                print(f"LightGBM unavailable; continuing without it: {e}", file=sys.stderr)
                self.lgbm = None

        self.model_names = ["ridge", "extra", "hist"]
        if self.lgbm is not None:
            self.model_names.append("lightgbm")

    def _matrices(self, records: Sequence[Record]):
        from scipy.sparse import csr_matrix, hstack
        Xd = self._dense_matrix(records, fit_names=False)
        texts = self._text_list(records)
        Xc = self.char_vec.transform(texts)
        Xw = self.word_vec.transform(texts)
        Xds = self.scaler.transform(Xd).astype(np.float32)
        Xs = hstack([Xc, Xw, csr_matrix(Xds)], format="csr")
        return Xd, Xs

    def base_predict_log(self, records: Sequence[Record]) -> np.ndarray:
        Xd, Xs = self._matrices(records)
        preds = [
            np.asarray(self.ridge.predict(Xs), dtype=float),
            np.asarray(self.extra.predict(Xd), dtype=float),
            np.asarray(self.hist.predict(Xd), dtype=float),
        ]
        if self.lgbm is not None:
            preds.append(np.asarray(self.lgbm.predict(Xd), dtype=float))
        return np.column_stack(preds)

    def fit_blender(self, calibration_records: Sequence[Record]) -> None:
        from sklearn.linear_model import LinearRegression
        P = self.base_predict_log(calibration_records)
        y = np.log(np.maximum(
            1.0,
            np.asarray([r.speech_tokens for r in calibration_records], dtype=float),
        ))
        blender = LinearRegression(positive=True)
        blender.fit(P, y)
        coef = np.asarray(blender.coef_, dtype=float)
        # Avoid a pathological all-zero positive solution.
        if not np.isfinite(coef).all() or coef.sum() <= 1e-8:
            coef = np.ones(P.shape[1], dtype=float) / P.shape[1]
            intercept = 0.0
        else:
            intercept = float(blender.intercept_)
        self.blender_coef = coef
        self.blender_intercept = intercept

    def set_blender(self, coef: np.ndarray, intercept: float) -> None:
        self.blender_coef = np.asarray(coef, dtype=float)
        self.blender_intercept = float(intercept)

    def predict_records_tokens(self, records: Sequence[Record]) -> np.ndarray:
        P = self.base_predict_log(records)
        if self.blender_coef is None:
            z = np.mean(P, axis=1)
        else:
            # In case LightGBM availability changed between fitting objects,
            # use the overlapping predictors only and renormalize coefficients.
            n = min(P.shape[1], len(self.blender_coef))
            coef = self.blender_coef[:n].copy()
            if coef.sum() > 0:
                # Preserve relative weights; intercept remains from calibration.
                pass
            z = P[:, :n] @ coef + self.blender_intercept
        return np.maximum(1.0, np.exp(z))

    def predict_tokens(self, text: str, exaggeration: float, cfg_weight: float) -> float:
        rec = Record("", text, float(exaggeration), float(cfg_weight), 1.0, 0.04)
        return float(self.predict_records_tokens([rec])[0])

    def predict_seconds(self, text: str, exaggeration: float, cfg_weight: float) -> float:
        return self.predict_tokens(text, exaggeration, cfg_weight) / self.token_rate


def grouped_split(records: Sequence[Record], random_seed: int, test_size: float, cal_size: float):
    from sklearn.model_selection import GroupShuffleSplit

    idx = np.arange(len(records))
    groups = np.asarray([r.text_id for r in records])

    split1 = GroupShuffleSplit(
        n_splits=1, test_size=test_size, random_state=random_seed
    )
    traincal_idx, test_idx = next(split1.split(idx, groups=groups))

    # cal_size is a fraction of the full dataset.
    relative_cal = cal_size / max(1e-9, 1.0 - test_size)
    groups_traincal = groups[traincal_idx]
    split2 = GroupShuffleSplit(
        n_splits=1, test_size=relative_cal, random_state=random_seed + 1
    )
    train_rel, cal_rel = next(split2.split(traincal_idx, groups=groups_traincal))
    train_idx = traincal_idx[train_rel]
    cal_idx = traincal_idx[cal_rel]

    def take(indices):
        return [records[int(i)] for i in indices]

    return take(train_idx), take(cal_idx), take(test_idx)


def print_metrics(title: str, metrics: dict) -> None:
    print(f"\n{title}")
    print("-" * len(title))
    for k, v in metrics.items():
        if isinstance(v, float):
            print(f"{k:24s}: {v:.6f}")
        else:
            print(f"{k:24s}: {v}")


def train_model(args) -> None:
    import joblib

    records = load_records(args.data)
    if len({r.text_id for r in records}) < 30:
        raise ValueError(
            "Too few unique texts. Use at least ~100 unique texts; for high "
            "accuracy, use 1000+ domain-matched chunks."
        )

    train, cal, test = grouped_split(
        records,
        random_seed=args.random_seed,
        test_size=args.test_size,
        cal_size=args.cal_size,
    )

    print(
        f"Rows: train={len(train)}, calibration={len(cal)}, test={len(test)}\n"
        f"Unique texts: train={len({r.text_id for r in train})}, "
        f"cal={len({r.text_id for r in cal})}, "
        f"test={len({r.text_id for r in test})}"
    )

    eval_model = DurationEnsemble(random_seed=args.random_seed)
    print("Fitting base models...", flush=True)
    eval_model.fit_base(train, use_lightgbm=not args.no_lightgbm)
    print("Fitting ensemble blender on held-out calibration texts...", flush=True)
    eval_model.fit_blender(cal)

    y_test = np.asarray([r.speech_tokens for r in test], dtype=float)
    pred_test = eval_model.predict_records_tokens(test)
    metrics = regression_metrics(y_test, pred_test, token_rate=25.0)
    print_metrics("HELD-OUT GROUPED TEST METRICS", metrics)

    # Duration buckets reveal whether short clips are causing large relative errors.
    durations = y_test / 25.0
    buckets = [
        (0, 3), (3, 6), (6, 12), (12, 20), (20, 40), (40, float("inf"))
    ]
    for lo, hi in buckets:
        mask = (durations >= lo) & (durations < hi)
        if mask.sum() >= 5:
            name = f"{lo:g}–{'∞' if math.isinf(hi) else f'{hi:g}'} sec"
            print_metrics(
                f"TEST BUCKET {name}",
                regression_metrics(y_test[mask], pred_test[mask], 25.0),
            )

    # Production model gets train + calibration; test remains untouched.
    production_records = train + cal
    final_model = DurationEnsemble(random_seed=args.random_seed)
    print("\nRefitting production base models on train + calibration...", flush=True)
    final_model.fit_base(production_records, use_lightgbm=not args.no_lightgbm)
    final_model.set_blender(
        eval_model.blender_coef.copy(),
        eval_model.blender_intercept,
    )
    final_model.metadata = {
        "created_unix": time.time(),
        "training_rows": len(production_records),
        "heldout_rows": len(test),
        "unique_training_texts": len({r.text_id for r in production_records}),
        "test_metrics": metrics,
        "target": "Chatterbox T3 speech-token count",
        "token_rate_hz": 25.0,
        "notes": (
            "Pure learned predictions are not guaranteed <1% for every utterance. "
            "Use ChatterboxTokenProbe for final frame-level timing."
        ),
    }

    out = Path(args.model)
    out.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(final_model, out, compress=3)
    print(f"\nSaved: {out}")

    if args.require_mape is not None and metrics["mape_percent"] > args.require_mape:
        raise SystemExit(
            f"Validation MAPE {metrics['mape_percent']:.3f}% exceeds "
            f"required {args.require_mape:.3f}%."
        )
    if args.require_max_ape is not None and metrics["max_ape_percent"] > args.require_max_ape:
        raise SystemExit(
            f"Validation max APE {metrics['max_ape_percent']:.3f}% exceeds "
            f"required {args.require_max_ape:.3f}%."
        )


