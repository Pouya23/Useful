WORD_RE = re.compile(r"[A-Za-z]+(?:['’-][A-Za-z]+)*|\d+(?:[.,]\d+)*")
SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+")
VOWEL_GROUP_RE = re.compile(r"[aeiouy]+", re.I)
ACRONYM_RE = re.compile(r"\b(?:[A-Z]\.?){2,}\b")
NUMBER_RE = re.compile(r"\b\d+(?:[.,]\d+)*(?:%|°[CF])?\b")
URL_RE = re.compile(r"(?:https?://|www\.)\S+", re.I)
EMAIL_RE = re.compile(r"\b[\w.+-]+@[\w.-]+\.[A-Za-z]{2,}\b")


def normalize_space(text: str) -> str:
    return re.sub(r"\s+", " ", str(text)).strip()


def normalize_key(text: str) -> str:
    t = normalize_space(text).lower().replace("’", "'")
    return hashlib.sha1(t.encode("utf-8")).hexdigest()


def words(text: str) -> list[str]:
    return WORD_RE.findall(text)


def hard_wrap(text: str, max_chars: int = 280) -> list[str]:
    """Sentence-aware splitting similar to the montage pipeline."""
    text = normalize_space(text)
    if not text:
        return []
    sentences = [s.strip() for s in SENTENCE_SPLIT_RE.split(text) if s.strip()]
    if not sentences:
        sentences = [text]

    pieces: list[str] = []
    for sentence in sentences:
        if len(sentence) <= max_chars:
            pieces.append(sentence)
            continue

        # Prefer clauses, then words.
        clauses = re.split(r"(?<=[,;:])\s+", sentence)
        cur = ""
        for clause in clauses:
            if len(clause) > max_chars:
                for w in clause.split():
                    proposal = w if not cur else cur + " " + w
                    if len(proposal) <= max_chars:
                        cur = proposal
                    else:
                        if cur:
                            pieces.append(cur)
                        cur = w
            else:
                proposal = clause if not cur else cur + " " + clause
                if len(proposal) <= max_chars:
                    cur = proposal
                else:
                    if cur:
                        pieces.append(cur)
                    cur = clause
        if cur:
            pieces.append(cur)

    out: list[str] = []
    cur = ""
    for piece in pieces:
        proposal = piece if not cur else cur + " " + piece
        if len(proposal) <= max_chars:
            cur = proposal
        else:
            if cur:
                out.append(cur)
            cur = piece
    if cur:
        out.append(cur)
    return [x for x in out if x]


