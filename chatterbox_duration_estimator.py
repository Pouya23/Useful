def estimate_duration(
    text: str,
    exaggeration: float,
    cfg_weight: float,
) -> float:
    """
    Drop-in adapter for safety_montage_narrator.py.

    Configure:
        export CHATTERBOX_DURATION_MODEL=/path/duration_model.joblib
    """
    global _CACHED_MODEL_PATH, _CACHED_MODEL
    path = os.environ.get("CHATTERBOX_DURATION_MODEL")
    if not path:
        # Graceful fallback makes the function importable before training.
        return heuristic_duration(text, exaggeration, cfg_weight)

    path = str(Path(path).expanduser().resolve())
    if _CACHED_MODEL is None or _CACHED_MODEL_PATH != path:
        _CACHED_MODEL = load_duration_model(path)
        _CACHED_MODEL_PATH = path
    return _CACHED_MODEL.predict_seconds(text, exaggeration, cfg_weight)


