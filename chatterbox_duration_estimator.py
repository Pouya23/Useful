def set_all_seeds(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    import torch
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)


class ChatterboxTokenProbe:
    """
    Loads original English Chatterbox and exposes its T3 speech-token sequence.

    This intentionally mirrors ChatterboxTTS.generate up to (but not including)
    S3Gen decoding.
    """

    def __init__(
        self,
        device: str = "cuda",
        voice_ref: Optional[str] = None,
    ):
        import torch
        import torch.nn.functional as F
        from chatterbox.tts import ChatterboxTTS, punc_norm
        try:
            from chatterbox.models.s3tokenizer import S3_TOKEN_RATE, drop_invalid_tokens
        except ImportError:
            # Older package variants exposed drop_invalid_tokens elsewhere.
            from chatterbox.models.s3tokenizer import drop_invalid_tokens
            S3_TOKEN_RATE = 25
        from chatterbox.models.t3.modules.cond_enc import T3Cond

        self.torch = torch
        self.F = F
        self.punc_norm = punc_norm
        self.drop_invalid_tokens = drop_invalid_tokens
        self.T3Cond = T3Cond
        self.token_rate = int(S3_TOKEN_RATE)
        self.device = device

        self.model = ChatterboxTTS.from_pretrained(device=device)
        self.voice_ref = voice_ref
        if voice_ref:
            self.model.prepare_conditionals(voice_ref, exaggeration=0.5)
        elif self.model.conds is None:
            raise ValueError(
                "No --voice-ref was supplied and this Chatterbox checkpoint "
                "does not contain built-in conditionals."
            )

    def _set_exaggeration(self, exaggeration: float) -> None:
        torch = self.torch
        old = self.model.conds.t3
        current = float(old.emotion_adv[0, 0, 0].item())
        if abs(current - float(exaggeration)) < 1e-8:
            return
        self.model.conds.t3 = self.T3Cond(
            speaker_emb=old.speaker_emb,
            cond_prompt_speech_tokens=old.cond_prompt_speech_tokens,
            emotion_adv=float(exaggeration) * torch.ones(1, 1, 1),
        ).to(device=self.model.device)

    @staticmethod
    def _speech_vocab_limit() -> int:
        # Current original Chatterbox uses valid S3 IDs < 6561.
        return 6561

    def probe_tokens(
        self,
        text: str,
        exaggeration: float = 0.5,
        cfg_weight: float = 0.5,
        temperature: float = 0.8,
        repetition_penalty: float = 1.2,
        min_p: float = 0.05,
        top_p: float = 1.0,
        seed: int = 1234,
        max_new_tokens: int = 1000,
    ):
        torch = self.torch
        F = self.F

        self._set_exaggeration(exaggeration)
        text = self.punc_norm(text)
        text_tokens = self.model.tokenizer.text_to_tokens(text).to(self.model.device)

        if cfg_weight > 0.0:
            text_tokens = torch.cat([text_tokens, text_tokens], dim=0)

        sot = self.model.t3.hp.start_text_token
        eot = self.model.t3.hp.stop_text_token
        text_tokens = F.pad(text_tokens, (1, 0), value=sot)
        text_tokens = F.pad(text_tokens, (0, 1), value=eot)

        set_all_seeds(seed)
        with torch.inference_mode():
            speech_tokens = self.model.t3.inference(
                t3_cond=self.model.conds.t3,
                text_tokens=text_tokens,
                max_new_tokens=max_new_tokens,
                temperature=temperature,
                cfg_weight=cfg_weight,
                repetition_penalty=repetition_penalty,
                min_p=min_p,
                top_p=top_p,
            )

        speech_tokens = speech_tokens[0]
        # Current drop_invalid_tokens implementations have differed slightly;
        # be defensive and then apply the explicit vocabulary bound.
        try:
            speech_tokens = self.drop_invalid_tokens(speech_tokens)
        except Exception:
            speech_tokens = speech_tokens[speech_tokens < self._speech_vocab_limit()]
        speech_tokens = speech_tokens[speech_tokens < self._speech_vocab_limit()]
        return speech_tokens.to(self.model.device)

    def token_duration_seconds(self, speech_tokens) -> float:
        return float(speech_tokens.numel()) / float(self.token_rate)

    def probe_duration(self, *args, **kwargs) -> tuple[float, int]:
        tokens = self.probe_tokens(*args, **kwargs)
        return self.token_duration_seconds(tokens), int(tokens.numel())

    def waveform_duration_from_tokens(self, speech_tokens) -> float:
        """Decode exactly these tokens and measure waveform duration."""
        torch = self.torch
        with torch.inference_mode():
            wav, _ = self.model.s3gen.inference(
                speech_tokens=speech_tokens,
                ref_dict=self.model.conds.gen,
            )
        return float(wav.shape[-1]) / float(self.model.sr)

    def save_tokens(self, speech_tokens, path: str | Path) -> None:
        self.torch.save(speech_tokens.detach().cpu(), str(path))

    def close(self) -> None:
        try:
            del self.model
        except Exception:
            pass
        gc.collect()
        if self.torch.cuda.is_available():
            self.torch.cuda.empty_cache()


