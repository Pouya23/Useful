def cmd_probe(args) -> None:
    import torch
    text = Path(args.text_file).read_text(encoding="utf-8") if args.text_file else args.text
    chunks = hard_wrap(text, args.max_chars)
    probe = ChatterboxTokenProbe(device=args.device, voice_ref=args.voice_ref)

    total = 0.0
    saved = []
    for i, chunk in enumerate(chunks):
        seed = args.seed + i
        toks = probe.probe_tokens(
            chunk,
            exaggeration=args.exaggeration,
            cfg_weight=args.cfg_weight,
            temperature=args.temperature,
            repetition_penalty=args.repetition_penalty,
            min_p=args.min_p,
            top_p=args.top_p,
            seed=seed,
            max_new_tokens=args.max_new_tokens,
        )
        sec = probe.token_duration_seconds(toks)
        total += sec
        print(
            f"chunk {i+1}: tokens={int(toks.numel())}, "
            f"duration={sec:.6f}s, seed={seed}"
        )
        if args.verify_waveform:
            wav_sec = probe.waveform_duration_from_tokens(toks)
            err = 100.0 * abs(wav_sec - sec) / max(wav_sec, 1e-9)
            print(f"          waveform={wav_sec:.6f}s, token-map error={err:.6f}%")
        saved.append(toks.detach().cpu())

    total += args.inter_chunk_pause * max(0, len(chunks) - 1)
    print(f"probe_total_seconds : {total:.6f}")

    if args.save_tokens:
        # A list is intentional because long narration is synthesized in chunks.
        torch.save(saved, args.save_tokens)
        print(f"saved token sequences to: {args.save_tokens}")
    probe.close()


