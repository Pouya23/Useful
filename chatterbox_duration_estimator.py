def cmd_search(args) -> None:
    model = load_duration_model(args.model)
    text = Path(args.text_file).read_text(encoding="utf-8") if args.text_file else args.text
    chunks = hard_wrap(text, args.max_chars)

    rows = []
    e = args.exag_min
    while e <= args.exag_max + 1e-9:
        c = args.cfg_min
        while c <= args.cfg_max + 1e-9:
            sec = sum(model.predict_seconds(x, e, c) for x in chunks)
            sec += args.inter_chunk_pause * max(0, len(chunks) - 1)
            err = abs(sec - args.target)
            # Small naturalness regularizer around 0.5/0.5.
            prior = ((e - 0.5) / 0.2) ** 2 + ((c - 0.5) / 0.2) ** 2
            score = err + args.naturalness_weight * prior
            rows.append((score, err, sec, e, c))
            c += args.step
        e += args.step

    rows.sort()
    for rank, (score, err, sec, e, c) in enumerate(rows[: args.top], 1):
        print(
            f"{rank:2d}. exag={e:.3f} cfg={c:.3f} "
            f"duration={sec:.4f}s abs_error={err:.4f}s score={score:.4f}"
        )



def cmd_synthesize_tokens(args) -> None:
    """
    Decode speech-token sequences saved by `probe --save-tokens`.

    This is the strongest timing mode: T3 is NOT re-run, so the waveform is
    decoded from exactly the token sequence whose duration was measured.
    """
    import torch
    import torchaudio as ta

    probe = ChatterboxTokenProbe(device=args.device, voice_ref=args.voice_ref)
    sequences = torch.load(args.tokens, map_location="cpu", weights_only=True)
    if torch.is_tensor(sequences):
        sequences = [sequences]
    if not isinstance(sequences, (list, tuple)) or not sequences:
        raise ValueError("Token file must contain one tensor or a non-empty list of tensors.")

    sr = int(probe.model.sr)
    silence = torch.zeros(
        (1, max(1, round(sr * args.inter_chunk_pause))),
        dtype=torch.float32,
    )
    waves = []
    token_seconds = 0.0

    for i, seq in enumerate(sequences):
        seq = torch.as_tensor(seq, dtype=torch.long, device=probe.model.device).reshape(-1)
        token_seconds += probe.token_duration_seconds(seq)

        with torch.inference_mode():
            wav, _ = probe.model.s3gen.inference(
                speech_tokens=seq,
                ref_dict=probe.model.conds.gen,
            )

        wav_np = wav.squeeze(0).detach().float().cpu().numpy()
        if not args.no_watermark:
            wav_np = probe.model.watermarker.apply_watermark(wav_np, sample_rate=sr)
        wav_t = torch.from_numpy(np.asarray(wav_np, dtype=np.float32)).reshape(1, -1)
        waves.append(wav_t)

        if i != len(sequences) - 1:
            waves.append(silence.clone())

    full = torch.cat(waves, dim=-1)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    ta.save(str(out), full, sr)

    actual_seconds = full.shape[-1] / float(sr)
    expected_seconds = (
        token_seconds
        + args.inter_chunk_pause * max(0, len(sequences) - 1)
    )
    ape = 100.0 * abs(actual_seconds - expected_seconds) / max(1e-9, actual_seconds)

    print(f"chunks                    : {len(sequences)}")
    print(f"token_predicted_seconds   : {expected_seconds:.9f}")
    print(f"waveform_actual_seconds   : {actual_seconds:.9f}")
    print(f"absolute_error_seconds    : {abs(actual_seconds - expected_seconds):.9f}")
    print(f"absolute_percent_error    : {ape:.9f}")
    print(f"output                    : {out}")
    probe.close()

