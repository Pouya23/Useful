def synthetic_text(rng: random.Random, min_words: int = 8, max_words: int = 55) -> str:
    target = rng.randint(min_words, max_words)
    sentences: list[str] = []

    while len(words(" ".join(sentences))) < target:
        subject = rng.choice(SUBJECTS)
        action = rng.choice(ACTIONS)
        context = rng.choice(CONTEXTS)
        structure = rng.randrange(6)

        if structure == 0:
            s = f"{subject.capitalize()} should {action} {context}."
        elif structure == 1:
            s = f"{rng.choice(TRANSITIONS)}, {action} {context}; check the surrounding area first."
        elif structure == 2:
            s = f"Warning: {action}. {rng.choice(CONSEQUENCES)}"
        elif structure == 3:
            n = rng.choice([2, 3, 5, 10, 15, 30])
            s = f"{action.capitalize()} {context}, and maintain at least {n} feet of clearance when the posted rule requires it."
        elif structure == 4:
            s = f"Before continuing, {action}; then confirm that nearby {rng.choice(SUBJECTS)} understand the restriction."
        else:
            s = f"{action.capitalize()} {context}. {rng.choice(CONSEQUENCES)}"

        if rng.random() < 0.12:
            s += f" Section {rng.randint(1, 12)}.{rng.randint(1, 9)} may provide additional instructions."
        if rng.random() < 0.08:
            s += " PPE requirements can change with the task."
        sentences.append(s)

    out = normalize_space(" ".join(sentences))
    if len(out) > 280:
        chunks = hard_wrap(out, 280)
        out = rng.choice(chunks)
    return out


def read_corpus(paths: Sequence[str], max_chars: int = 280) -> list[str]:
    out: list[str] = []
    for pstr in paths:
        p = Path(pstr)
        raw = p.read_text(encoding="utf-8", errors="replace")

        if p.suffix.lower() == ".jsonl":
            items = []
            for line in raw.splitlines():
                if not line.strip():
                    continue
                obj = json.loads(line)
                if isinstance(obj, dict) and isinstance(obj.get("text"), str):
                    items.append(obj["text"])
                elif isinstance(obj, str):
                    items.append(obj)
            raw_blocks = items
        else:
            # Preserve paragraphs but also handle one-text-per-line corpora.
            raw_blocks = [x.strip() for x in re.split(r"\n\s*\n|\n", raw) if x.strip()]

        for block in raw_blocks:
            for chunk in hard_wrap(block, max_chars=max_chars):
                if 3 <= len(words(chunk)) <= 90:
                    out.append(chunk)

    seen: set[str] = set()
    unique: list[str] = []
    for t in out:
        k = normalize_key(t)
        if k not in seen:
            seen.add(k)
            unique.append(t)
    return unique


