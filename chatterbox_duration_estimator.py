#!/usr/bin/env python3
"""
Chatterbox duration estimator
=============================

A high-accuracy duration-estimation toolkit for the original English
ResembleAI Chatterbox TTS model (the model with exaggeration + cfg_weight).

It provides three accuracy levels:

1) heuristic
   Zero-training fallback. Fast, but not intended for precision work.

2) learned
   Trains an ensemble on T3 speech-token counts generated by YOUR exact
   Chatterbox voice and parameter range.  The model predicts speech-token
   count, then converts it to seconds using Chatterbox's 25 Hz speech-token
   rate.

3) probe
   Runs Chatterbox's autoregressive T3 stage but skips S3Gen waveform
   decoding.  This obtains the actual generated speech-token count.
   Because Chatterbox speech tokens are 25 Hz, this is the closest thing
   to an exact pre-vocoder duration prediction.  For a hard guarantee,
   reuse the probed speech tokens for waveform synthesis rather than
   re-running T3.

IMPORTANT
---------
A universal "<1% error for every utterance, no matter the duration" guarantee
is impossible for a pure text regressor.  For a 1-second utterance, 1% is only
10 ms, smaller than one Chatterbox speech-token frame (40 ms).

If you need near-exact final timing:
  * use the learned model for the large parameter/text search;
  * use T3 token probing for the final few candidates;
  * synthesize the selected candidate from the SAME probed token sequence.

The learned model is deliberately trained/tested with GROUP SPLITS BY TEXT.
Different exaggeration/CFG versions of the same sentence can never appear in
both train and test sets.

Typical workflow
----------------

# 1. Build calibration data.  Using your real narration corpus is strongly
#    recommended. One text per line or ordinary paragraphs are accepted.
python chatterbox_duration_estimator.py collect \
    --voice-ref voice.wav \
    --corpus narration_corpus.txt \
    --out duration_data.csv \
    --texts 1800 \
    --variants-per-text 5 \
    --device cuda

# 2. Train + evaluate
python chatterbox_duration_estimator.py train \
    --data duration_data.csv \
    --model duration_model.joblib

# 3. Fast prediction
python chatterbox_duration_estimator.py predict \
    --model duration_model.joblib \
    --text "Keep a safe distance from moving machinery." \
    --exaggeration 0.50 \
    --cfg-weight 0.50

# 4. T3-only final probe
python chatterbox_duration_estimator.py probe \
    --voice-ref voice.wav \
    --text "Keep a safe distance from moving machinery." \
    --exaggeration 0.50 \
    --cfg-weight 0.50 \
    --seed 1234

Integration with safety_montage_narrator.py
-------------------------------------------
Set:

    export CHATTERBOX_DURATION_MODEL=/absolute/path/duration_model.joblib

Then use:

    --estimator chatterbox_duration_estimator:estimate_duration

The function:
    estimate_duration(text, exaggeration, cfg_weight) -> float
matches the adapter expected by the montage pipeline.
"""

